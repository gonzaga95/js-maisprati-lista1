console.log("A sequência de Fibonacci é uma série de números onde cada número é a soma dos dois anteriores. A sequência começa com... ");

function fibonacci(n) {
  if (n <= 0) {
    return [];
  } else if (n === 1) {
    return [0];
  } else if (n === 2) {
    return [0, 1];
  } else {
    const fib = [0, 1];
    for (let i = 2; i < n; i++) {
      fib[i] = fib[i - 1] + fib[i - 2];
    }
    return fib;
  }
}
console.log(fibonacci(10));